#!/usr/bin/env node
// Generates src/components/KimiMascot/guardEyesShapes.ts from assets/mascot/guard-eyes.svg
// (the eyes of the "guard" pose, drawn 1:1 over guard-no-eyes.png). Run after the design
// changes the SVG: `node scripts/brand/mascot-eyes.mjs`. `--check` fails when the file is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SOURCE = path.join(root, 'assets/mascot/guard-eyes.svg');
const OUT = path.join(root, 'src/components/KimiMascot/guardEyesShapes.ts');

/** Minimal XML parser: elements and attributes only (comments and metadata dropped). */
function parse(xml) {
  const body = xml.replace(/<metadata>[\s\S]*?<\/metadata>/g, '').replace(/<!--[\s\S]*?-->/g, '');
  const rootNode = { tag: '#root', attrs: {}, children: [] };
  const stack = [rootNode];
  const re = /<(\/?)([a-zA-Z][\w:-]*)([^>]*?)(\/?)>/g;
  let m;
  while ((m = re.exec(body))) {
    const [, closing, tag, rawAttrs, selfClosing] = m;
    if (closing) {
      stack.pop();
      continue;
    }
    const attrs = {};
    for (const a of rawAttrs.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    const node = { tag, attrs, children: [] };
    stack[stack.length - 1].children.push(node);
    if (!selfClosing) stack.push(node);
  }
  return rootNode;
}

function find(node, id) {
  if (node.attrs.id === id) return node;
  for (const child of node.children) {
    const hit = find(child, id);
    if (hit) return hit;
  }
  return null;
}

function need(tree, id) {
  const node = find(tree, id);
  if (!node) throw new Error(`guard-eyes.svg: #${id} not found`);
  return node;
}

const num = (v) => Number(v);
const circle = (c) => ({ cx: num(c.attrs.cx), cy: num(c.attrs.cy), r: num(c.attrs.r), fill: c.attrs.fill });
const tree = parse(fs.readFileSync(SOURCE, 'utf8'));

function eye(side) {
  const white = need(tree, `eye-${side}-white`);
  const shade = need(tree, `eye-${side}-shade`);
  const pupil = need(tree, `pupil-${side}`);
  const lid = need(tree, `eyelid-${side}`).children[0];
  const angry = need(tree, `brow-${side}-angry`);
  const brow = need(tree, `brow-${side}`);
  return {
    clip: need(tree, `clip-eye-${side}`).children[0].attrs.d,
    white: { d: white.attrs.d, fill: white.attrs.fill },
    shade: {
      d: shade.attrs.d,
      stroke: shade.attrs.stroke,
      strokeWidth: num(shade.attrs['stroke-width']),
      opacity: num(shade.attrs.opacity),
    },
    pupil: circle(pupil.children[0]),
    shine: circle(need(tree, `shine-${side}`)),
    eyelid: {
      x: num(lid.attrs.x),
      y: num(lid.attrs.y),
      width: num(lid.attrs.width),
      height: num(lid.attrs.height),
      fill: lid.attrs.fill,
    },
    browAngry: angry.children.map((c) => ({ d: c.attrs.d, fill: c.attrs.fill })),
    brow: { d: brow.attrs.d, fill: brow.attrs.fill },
  };
}

const svg = tree.children[0];
const data = {
  viewBox: svg.attrs.viewBox,
  rootTransform: need(tree, 'eyes-root').attrs.transform,
  left: eye('left'),
  right: eye('right'),
};

const out = `// Generated by scripts/brand/mascot-eyes.mjs from assets/mascot/guard-eyes.svg. Do not edit.

interface Circle {
  cx: number;
  cy: number;
  r: number;
  fill: string;
}

export interface GuardEye {
  clip: string;
  white: { d: string; fill: string };
  shade: { d: string; stroke: string; strokeWidth: number; opacity: number };
  pupil: Circle;
  shine: Circle;
  eyelid: { x: number; y: number; width: number; height: number; fill: string };
  browAngry: { d: string; fill: string }[];
  brow: { d: string; fill: string };
}

export const GUARD_EYES: { viewBox: string; rootTransform: string; left: GuardEye; right: GuardEye } = ${JSON.stringify(data, null, 2)};
`;

const args = process.argv.slice(2);
if (args.some((a) => a !== '--check')) {
  console.error('Usage: node scripts/brand/mascot-eyes.mjs [--check]');
  process.exit(1);
}

if (args.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('guardEyesShapes.ts is stale: run node scripts/brand/mascot-eyes.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(OUT, out);
  console.log(`Wrote ${path.relative(root, OUT)}`);
}

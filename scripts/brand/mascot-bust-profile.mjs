#!/usr/bin/env node
// Generates src/components/KimiMascot/bustProfile.ts: for each pose, the right edge of the
// drawing inside its bust window (BUST_WINDOWS in poses.ts), per horizontal band, as a
// fraction of the window width. The feedback sheet uses it to start the text after whatever
// part of the mascot (body, headband tips, fists) is at the text's height.
// Run after changing the windows or the art: `node scripts/brand/mascot-bust-profile.mjs`.
// `--check` fails when the file is stale.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(import.meta.url);
const { PNG } = require('pngjs');

const POSES_TS = path.join(root, 'src/components/KimiMascot/poses.ts');
const OUT = path.join(root, 'src/components/KimiMascot/bustProfile.ts');
/** Bands per window height (top to bottom). */
const BANDS = 30;
/** Alpha above this counts as drawing. */
const ALPHA = 20;

const args = process.argv.slice(2);
if (args.some((a) => a !== '--check')) {
  console.error('Usage: node scripts/brand/mascot-bust-profile.mjs [--check]');
  process.exit(1);
}

// BUST_WINDOWS entries: `name: { x: 1, y: 2, width: 3, height: 4 }`.
const source = fs.readFileSync(POSES_TS, 'utf8');
const block = source.slice(source.indexOf('BUST_WINDOWS'));
const windows = {};
for (const m of block.matchAll(/(\w+): \{ x: (\d+), y: (\d+), width: (\d+), height: (\d+) \}/g)) {
  if (windows[m[1]]) break;
  windows[m[1]] = { x: +m[2], y: +m[3], width: +m[4], height: +m[5] };
}

const profile = {};
for (const [pose, w] of Object.entries(windows)) {
  const png = PNG.sync.read(fs.readFileSync(path.join(root, `assets/mascot/${pose}.png`)));
  const bands = [];
  for (let b = 0; b < BANDS; b++) {
    const y0 = Math.floor(w.y + (b * w.height) / BANDS);
    const y1 = Math.min(Math.floor(w.y + ((b + 1) * w.height) / BANDS), png.height);
    let right = -1;
    for (let y = y0; y < y1; y++) {
      for (let x = Math.min(w.x + w.width, png.width) - 1; x > right; x--) {
        if (png.data[(y * png.width + x) * 4 + 3] > ALPHA) {
          right = x;
          break;
        }
      }
    }
    bands.push(right < 0 ? 0 : Math.round(((right + 1 - w.x) / w.width) * 1000) / 1000);
  }
  profile[pose] = bands;
}

const body = Object.entries(profile)
  .map(([pose, bands]) => `  ${pose}: [${bands.join(', ')}],`)
  .join('\n');
const out = `// Generated by scripts/brand/mascot-bust-profile.mjs from assets/mascot/*.png and
// BUST_WINDOWS (poses.ts). Do not edit.
import type { KimiPose } from './poses';

/** Bands per bust window height, top to bottom. */
export const BUST_PROFILE_BANDS = ${BANDS};

/** Right edge of the drawing in each band, as a fraction of the bust window width. */
export const BUST_RIGHT_PROFILE: Record<KimiPose, readonly number[]> = {
${body}
};
`;

if (args.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('bustProfile.ts is stale: run node scripts/brand/mascot-bust-profile.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(OUT, out);
  console.log(`Wrote ${path.relative(root, OUT)}`);
}

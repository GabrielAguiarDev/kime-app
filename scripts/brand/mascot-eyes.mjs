#!/usr/bin/env node
// Generates src/components/KimiMascot/eyeShapes.ts from every assets/mascot/{pose}-eyes.svg
// (the eyes of that pose, drawn 1:1 over {pose}-no-eyes.png). Run after the design changes an
// SVG: `node scripts/brand/mascot-eyes.mjs`. `--check` fails when the file is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const MASCOT = path.join(root, 'assets/mascot');
const OUT = path.join(root, 'src/components/KimiMascot/eyeShapes.ts');
const POSES = fs.readdirSync(MASCOT).filter((f) => f.endsWith('-eyes.svg')).map((f) => f.slice(0, -'-eyes.svg'.length)).sort();

/** Minimal XML parser: elements and attributes only (comments and metadata dropped). */
function parse(xml) {
  const body = xml.replace(/<metadata>[\s\S]*?<\/metadata>/g, '').replace(/<!--[\s\S]*?-->/g, '');
  const rootNode = { tag: '#root', attrs: {}, children: [] };
  const stack = [rootNode];
  const re = /<(\/?)([a-zA-Z][\w:-]*)([^>]*?)(\/?)>/g;
  let m;
  while ((m = re.exec(body))) {
    const [, closing, tag, rawAttrs, selfClosing] = m;
    if (closing) {
      stack.pop();
      continue;
    }
    const attrs = {};
    for (const a of rawAttrs.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    const node = { tag, attrs, children: [] };
    stack[stack.length - 1].children.push(node);
    if (!selfClosing) stack.push(node);
  }
  return rootNode;
}

function find(node, id) {
  if (node.attrs.id === id) return node;
  for (const child of node.children) {
    const hit = find(child, id);
    if (hit) return hit;
  }
  return null;
}

let current = '';
function need(tree, id) {
  const node = find(tree, id);
  if (!node) throw new Error(`${current}-eyes.svg: #${id} not found`);
  return node;
}

const num = (v) => Number(v);
const circle = (c) => ({ cx: num(c.attrs.cx), cy: num(c.attrs.cy), r: num(c.attrs.r), fill: c.attrs.fill });

function eye(tree, side) {
  const white = need(tree, `eye-${side}-white`);
  const shade = need(tree, `eye-${side}-shade`);
  const pupil = need(tree, `pupil-${side}`);
  const lidGroup = need(tree, `eyelid-${side}`);
  const lid = lidGroup.children[0];
  const pupilShape = pupil.children[0];
  const angry = need(tree, `brow-${side}-angry`);
  const brow = need(tree, `brow-${side}`);
  return {
    clip: need(tree, `clip-eye-${side}`).children[0].attrs.d,
    white: { d: white.attrs.d, fill: white.attrs.fill },
    shade: {
      d: shade.attrs.d,
      stroke: shade.attrs.stroke,
      strokeWidth: num(shade.attrs['stroke-width']),
      opacity: num(shade.attrs.opacity),
    },
    // Circle (guard) or rotated ellipse: always written as an ellipse.
    pupil: pupilShape.tag === 'ellipse'
      ? {
          cx: num(pupilShape.attrs.cx),
          cy: num(pupilShape.attrs.cy),
          rx: num(pupilShape.attrs.rx),
          ry: num(pupilShape.attrs.ry),
          angle: num(/rotate\(([-\d.]+)/.exec(pupilShape.attrs.transform ?? '')?.[1] ?? 0),
          fill: pupilShape.attrs.fill,
        }
      : (({ cx, cy, r, fill }) => ({ cx, cy, rx: r, ry: r, angle: 0, fill }))(circle(pupilShape)),
    shine: circle(need(tree, `shine-${side}`)),
    eyelid: {
      x: num(lid.attrs.x),
      y: num(lid.attrs.y),
      width: num(lid.attrs.width),
      height: num(lid.attrs.height),
      fill: lid.attrs.fill,
      // Optional rotation of the eyelid, so it closes along a tilted lid line.
      transform: lidGroup.attrs.transform ?? null,
    },
    browAngry: angry.children.map((c) => ({ d: c.attrs.d, fill: c.attrs.fill })),
    brow: { d: brow.attrs.d, fill: brow.attrs.fill },
  };
}

const shapes = {};
for (const pose of POSES) {
  current = pose;
  const tree = parse(fs.readFileSync(path.join(MASCOT, `${pose}-eyes.svg`), 'utf8'));
  shapes[pose] = {
    viewBox: tree.children[0].attrs.viewBox,
    rootTransform: need(tree, 'eyes-root').attrs.transform,
    left: eye(tree, 'left'),
    right: eye(tree, 'right'),
  };
}

const out = `// Generated by scripts/brand/mascot-eyes.mjs from assets/mascot/{pose}-eyes.svg. Do not edit.

interface Circle {
  cx: number;
  cy: number;
  r: number;
  fill: string;
}

export interface MascotEye {
  clip: string;
  white: { d: string; fill: string };
  shade: { d: string; stroke: string; strokeWidth: number; opacity: number };
  /** Ellipse rotated by \`angle\` degrees about its centre (a circle when rx = ry). */
  pupil: { cx: number; cy: number; rx: number; ry: number; angle: number; fill: string };
  shine: Circle;
  /** Closed position; \`transform\` tilts it along the lid line. */
  eyelid: { x: number; y: number; width: number; height: number; fill: string; transform: string | null };
  browAngry: { d: string; fill: string }[];
  brow: { d: string; fill: string };
}

export interface MascotEyesShape {
  viewBox: string;
  rootTransform: string;
  left: MascotEye;
  right: MascotEye;
}

export const EYES_POSES = ${JSON.stringify(POSES)} as const;
export type EyesPose = (typeof EYES_POSES)[number];

export const MASCOT_EYES: Record<EyesPose, MascotEyesShape> = ${JSON.stringify(shapes, null, 2)};
`;

const args = process.argv.slice(2);
if (args.some((a) => a !== '--check')) {
  console.error('Usage: node scripts/brand/mascot-eyes.mjs [--check]');
  process.exit(1);
}

if (args.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('eyeShapes.ts is stale: run node scripts/brand/mascot-eyes.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(OUT, out);
  console.log(`Wrote ${path.relative(root, OUT)}`);
}
